#!/usr/bin/env node
// Read-only report on the collections index, per wing: what is published under
// each facet, what is built but not listed, and what wants an editor's eye
// (tags with no facet assigned, terms close to their threshold, author names
// that look like two spellings of one person). Writes nothing.
//
//   npm run collections:report

const { loadCatalogSync, loadWings } = require('./utils/catalog');
const { getIndex } = require('./utils/collections-index');
const { buildTagCollectionsByWing } = require('./utils/tag-collections');
const { derivedTerms } = require('./utils/derived-terms');
const { THRESHOLD, FACET_THRESHOLD, FACETS, TAG_FACETS, slugifyTag, resolveAlias } = require('./utils/tag-vocabulary');

const NEAR = 3;

const index = getIndex();
const books = loadCatalogSync().data;
const wingBySlug = new Map(loadWings().map(w => [w.slug, w]));
const wingOf = book => book.collection || index.defaultWing;

// Every term in every wing, whatever its size, grouped as the pages are.
const allTerms = buildTagCollectionsByWing(books, {
  defaultWing: index.defaultWing,
  threshold: 1,
  derive: book => derivedTerms(book, wingBySlug.get(wingOf(book))),
  hasCover: () => false,
});

const assigned = new Set(Object.values(TAG_FACETS).flat().map(slugifyTag));
const thresholdOf = facet => FACET_THRESHOLD[facet] || THRESHOLD;
const line = (name, count, note) => `    ${String(count).padStart(5)}  ${name}${note ? `  (${note})` : ''}`;

// Edit distance, for first names only. This flags pairs for a person to look
// at; it never decides which books a page lists.
function distance(a, b) {
  const row = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    let prev = row[0];
    row[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const next = Math.min(row[j] + 1, row[j - 1] + 1, prev + (a[i - 1] === b[j - 1] ? 0 : 1));
      prev = row[j];
      row[j] = next;
    }
  }
  return row[b.length];
}

// Two first names that could be one person: an initial or a shortening of the
// other ("J." and "John"), or a letter or two apart ("Stephen" and "Steven").
function sameFirstName(a, b) {
  const [x, y] = [a, b].map(n => n.toLowerCase().replace(/[^\p{L}\p{N}]/gu, ''));
  if (!x || !y || x === y) return false;
  return x.startsWith(y) || y.startsWith(x) || distance(x, y) <= 2;
}

function personVariants(wing) {
  const byLast = new Map();
  books.filter(b => wingOf(b) === wing).forEach(book => {
    const person = derivedTerms(book, wingBySlug.get(wing)).find(t => t.rule === 'person');
    if (!person) return;
    const last = slugifyTag(book.author_last.trim());
    const firsts = byLast.get(last) || byLast.set(last, new Map()).get(last);
    // Spellings that already share a page (accents, case, an alias) are one entry.
    const key = slugifyTag(resolveAlias(person.name));
    const seen = firsts.get(key) || firsts.set(key, { name: person.name, first: book.author_first.trim(), count: 0 }).get(key);
    seen.count++;
  });

  const pairs = [];
  byLast.forEach(firsts => {
    const people = [...firsts.values()];
    people.forEach((a, i) => people.slice(i + 1).forEach(b => {
      if (sameFirstName(a.first, b.first)) pairs.push(`${a.name} (${a.count}) / ${b.name} (${b.count})`);
    }));
  });
  return pairs.sort();
}

let noFacet = 0;

index.wings.forEach(wing => {
  const pages = index.pages.filter(p => p.wing === wing.slug);
  const generated = pages.filter(p => p.autoGenerated);
  const unlisted = pages.filter(p => !p.listed);
  const wingBooks = books.filter(b => wingOf(b) === wing.slug).length;

  console.log(`\n=== ${wing.name || wing.slug} (${wing.slug}): ${wingBooks} books, ${pages.length} pages, ${unlisted.length} not listed`);

  [...FACETS, { id: null, label: 'Curated collections' }].forEach(facet => {
    const group = (facet.id ? generated.filter(p => p.facet === facet.id) : pages.filter(p => !p.autoGenerated))
      .sort((a, b) => b.bookCount - a.bookCount || a.title.localeCompare(b.title));
    if (!group.length) return;
    console.log(`\n  ${facet.label} (${group.length})`);
    group.forEach(p => console.log(line(p.title, p.bookCount, p.listed ? p.origin : `${p.origin}, not listed`)));
  });

  if (unlisted.length) {
    console.log('\n  Built, not listed');
    unlisted.forEach(p => console.log(line(p.title, p.bookCount,
      p.sameAs ? `same books as ${p.sameAs.title}` : 'covers 90% or more of the wing')));
  }

  // A hand tag missing from TAG_FACETS is filed under Themes by default.
  const unassigned = (index.tagTier.get(wing.slug) || [])
    .filter(t => t.origin === 'hand' && !assigned.has(t.slug));
  noFacet += unassigned.length;
  if (unassigned.length) {
    console.log('\n  Published hand terms with no facet in TAG_FACETS');
    unassigned.forEach(t => console.log(line(t.title, t.bookCount)));
  }

  const targets = index.tagTargets[wing.slug];
  const terms = allTerms.get(wing.slug) || [];
  const below = terms
    .filter(t => !targets.has(t.slug) && thresholdOf(t.facet) - t.bookCount <= NEAR)
    .filter(t => t.bookCount < thresholdOf(t.facet));
  const above = generated.filter(p => p.bookCount - thresholdOf(p.facet) <= NEAR);
  const byCount = (a, b) => b.bookCount - a.bookCount || a.title.localeCompare(b.title);
  if (below.length) {
    console.log(`\n  Up to ${NEAR} books short of a page`);
    below.sort(byCount).forEach(t => console.log(line(t.title, t.bookCount, `${t.facet}, needs ${thresholdOf(t.facet)}`)));
  }
  if (above.length) {
    console.log(`\n  Pages no more than ${NEAR} books above their threshold`);
    above.sort(byCount).forEach(p => console.log(line(p.title, p.bookCount, `${p.facet}, needs ${thresholdOf(p.facet)}`)));
  }

  const variants = personVariants(wing.slug);
  if (variants.length) {
    console.log('\n  Author names that differ only by first-name spelling');
    variants.forEach(v => console.log(`    ${v}`));
  }
});

const unlistedTotal = index.pages.filter(p => !p.listed).length;
console.log(`\n${index.pages.length} pages (${index.summary}), ${unlistedTotal} built but not listed`);
console.log(`${noFacet} published hand terms without a facet`);
