#!/usr/bin/env node

/**
 * Richard Prince Collection Generator v2.0
 *
 * Orchestrates the complete process of generating a static HTML collection page
 * for Richard Prince books from the library's CSV database.
 *
 * FEATURES:
 * - Async/await throughout with Promise.all() for parallel processing
 * - Comprehensive error handling at every level
 * - Detailed progress logging with timestamps
 * - Prerequisite validation (directories, files, dependencies)
 * - Output verification after write
 * - Proper exit codes for CI/CD integration (0=success, 1=failure)
 * - Graceful degradation (continues on individual book failures)
 * - Modular architecture with lib/ imports
 *
 * USAGE:
 *   node scripts/generate-prince-collection-v2.js
 *
 * ENVIRONMENT:
 *   No environment variables required. Paths are configured below.
 *
 * EXIT CODES:
 *   0 - Success
 *   1 - Fatal error (missing prerequisites, parsing failure, write failure)
 *
 * DEPENDENCIES:
 *   - csv-parse (installed via package.json)
 *   - Node.js 18+ (for native fetch, ES modules)
 *
 * OUTPUT:
 *   Generates: src/collections/richard-prince.html
 *   Format: Eleventy template with frontmatter + HTML content
 *
 * PROCESS FLOW:
 *   1. Validate prerequisites (directories, CSV file)
 *   2. Read and parse CSV data
 *   3. Extract and filter Richard Prince books
 *   4. Transform and validate book records
 *   5. Sort books by year (desc) and title (asc)
 *   6. Generate secure HTML with proper escaping
 *   7. Write output file
 *   8. Verify output and report statistics
 *
 * @author Generated by Claude Code
 * @version 2.0.0
 * @license MIT
 */

import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import process from 'process';

// Import modular library functions
import {
  readCSVFile,
  writeHTMLFile,
  validatePrerequisites,
  fileExists,
} from '../lib/file-system-utils.js';

import {
  extractPrinceBooks,
  sortBooks,
} from '../lib/book-data-extractor.js';

import {
  generateCollectionPage,
  validateHTML,
} from '../lib/html-generator.js';

// Configuration
const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PROJECT_ROOT = resolve(__dirname, '../..');

const CONFIG = {
  csvFile: resolve(PROJECT_ROOT, 'src/_data/books.csv'),
  outputFile: resolve(PROJECT_ROOT, 'src/collections/richard-prince.html'),
  outputDir: resolve(PROJECT_ROOT, 'src/collections'),
  pageTitle: 'Richard Prince Collection',
  pageDescription: 'A curated collection of publications by and about Richard Prince, featuring artist books, exhibition catalogs, and monographs spanning his influential career.',
};

/**
 * Logger utility with timestamp prefixes
 */
const logger = {
  info: (msg) => console.log(`[${new Date().toISOString()}] INFO: ${msg}`),
  success: (msg) => console.log(`[${new Date().toISOString()}] ✓ SUCCESS: ${msg}`),
  warn: (msg) => console.warn(`[${new Date().toISOString()}] ⚠ WARNING: ${msg}`),
  error: (msg) => console.error(`[${new Date().toISOString()}] ✗ ERROR: ${msg}`),
  section: (msg) => console.log(`\n${'='.repeat(60)}\n${msg}\n${'='.repeat(60)}`),
};

/**
 * Validates that all prerequisites are met before processing
 *
 * @returns {Promise<boolean>} True if all prerequisites pass
 */
async function checkPrerequisites() {
  logger.section('Validating Prerequisites');

  const { valid, errors } = await validatePrerequisites({
    csvFile: CONFIG.csvFile,
    outputDir: CONFIG.outputDir,
  });

  if (!valid) {
    logger.error('Prerequisite validation failed:');
    errors.forEach(err => logger.error(`  - ${err}`));
    return false;
  }

  logger.success('All prerequisites validated');
  logger.info(`CSV file: ${CONFIG.csvFile}`);
  logger.info(`Output directory: ${CONFIG.outputDir}`);

  return true;
}

/**
 * Reads and parses the books CSV file
 *
 * @returns {Promise<string>} CSV content as string
 * @throws {Error} If file cannot be read
 */
async function loadCSVData() {
  logger.section('Loading CSV Data');

  try {
    logger.info('Reading books CSV...');
    const content = await readCSVFile(CONFIG.csvFile);

    const lineCount = content.split('\n').length;
    logger.success(`Loaded ${lineCount} lines from CSV`);

    return content;
  } catch (error) {
    logger.error(`Failed to load CSV: ${error.message}`);
    throw error;
  }
}

/**
 * Extracts, filters, and processes Richard Prince books
 *
 * @param {string} csvContent - Raw CSV content
 * @returns {Promise<Object[]>} Array of processed book objects
 */
async function processBooks(csvContent) {
  logger.section('Processing Books');

  try {
    logger.info('Extracting Richard Prince books...');
    const { books, errors } = await extractPrinceBooks(csvContent);

    if (errors.length > 0) {
      logger.warn(`Found ${errors.length} validation issues:`);
      errors.forEach(err => logger.warn(`  - ${err}`));
    }

    logger.success(`Extracted ${books.length} valid Richard Prince books`);

    // Log statistics
    const withImages = books.filter(b => b.image_url).length;
    const withYears = books.filter(b => b.publication_year).length;
    const withDescriptions = books.filter(b => b.description).length;

    logger.info(`Statistics:`);
    logger.info(`  - Books with cover images: ${withImages}/${books.length}`);
    logger.info(`  - Books with publication year: ${withYears}/${books.length}`);
    logger.info(`  - Books with descriptions: ${withDescriptions}/${books.length}`);

    return books;
  } catch (error) {
    logger.error(`Failed to process books: ${error.message}`);
    throw error;
  }
}

/**
 * Generates HTML content from processed books
 *
 * @param {Object[]} books - Array of book objects
 * @returns {Promise<string>} Generated HTML content
 */
async function generateHTML(books) {
  logger.section('Generating HTML');

  try {
    logger.info('Creating collection page...');
    const html = generateCollectionPage(books, {
      title: CONFIG.pageTitle,
      description: CONFIG.pageDescription,
    });

    logger.success(`Generated HTML (${html.length} characters)`);

    // Validate HTML structure
    logger.info('Validating HTML structure...');
    const { valid, errors } = validateHTML(html);

    if (!valid) {
      logger.warn('HTML validation warnings:');
      errors.forEach(err => logger.warn(`  - ${err}`));
    } else {
      logger.success('HTML structure validated');
    }

    return html;
  } catch (error) {
    logger.error(`Failed to generate HTML: ${error.message}`);
    throw error;
  }
}

/**
 * Writes HTML content to output file
 *
 * @param {string} html - HTML content to write
 * @returns {Promise<void>}
 */
async function writeOutput(html) {
  logger.section('Writing Output');

  try {
    logger.info(`Writing to: ${CONFIG.outputFile}`);
    await writeHTMLFile(CONFIG.outputFile, html);
    logger.success('File written successfully');

    // Verify output
    logger.info('Verifying output file...');
    const exists = await fileExists(CONFIG.outputFile);

    if (!exists) {
      throw new Error('Output file verification failed: file does not exist after write');
    }

    logger.success('Output file verified');
  } catch (error) {
    logger.error(`Failed to write output: ${error.message}`);
    throw error;
  }
}

/**
 * Main execution function
 *
 * Orchestrates the complete generation process with comprehensive
 * error handling and progress reporting.
 *
 * @returns {Promise<number>} Exit code (0=success, 1=failure)
 */
async function main() {
  const startTime = Date.now();

  logger.section('Richard Prince Collection Generator v2.0');
  logger.info('Starting generation process...');

  try {
    // Step 1: Validate prerequisites
    const prereqsValid = await checkPrerequisites();
    if (!prereqsValid) {
      logger.error('Cannot proceed without valid prerequisites');
      return 1;
    }

    // Step 2: Load CSV data
    const csvContent = await loadCSVData();

    // Step 3: Process books (parallel operations handled internally)
    const books = await processBooks(csvContent);

    if (books.length === 0) {
      logger.warn('No Richard Prince books found in CSV');
      logger.info('Exiting without generating collection page');
      return 0;
    }

    // Step 4: Generate HTML
    const html = await generateHTML(books);

    // Step 5: Write output
    await writeOutput(html);

    // Success summary
    const duration = ((Date.now() - startTime) / 1000).toFixed(2);
    logger.section('Generation Complete');
    logger.success(`Successfully generated Richard Prince collection page`);
    logger.info(`Output: ${CONFIG.outputFile}`);
    logger.info(`Books: ${books.length}`);
    logger.info(`Duration: ${duration}s`);

    return 0;
  } catch (error) {
    // Fatal error handling
    logger.section('Fatal Error');
    logger.error(error.message);

    if (error.stack) {
      logger.error('Stack trace:');
      console.error(error.stack);
    }

    const duration = ((Date.now() - startTime) / 1000).toFixed(2);
    logger.info(`Failed after ${duration}s`);

    return 1;
  }
}

// Execute main function and exit with appropriate code
main()
  .then(exitCode => {
    process.exit(exitCode);
  })
  .catch(error => {
    // Catch any unhandled errors
    logger.error('Unhandled error in main:');
    console.error(error);
    process.exit(1);
  });
